class AiFoundationTest extends TestCase
{
    use RefreshDatabase;

    private const LEVEL = 'https://workspace.openric.org/vocab/level-of-description/';

    private const PAGE = 'Minutes of the Riverside Parish Council meeting held on the third of May';

    private Institution $institution;

    private User $admin;

    private User $editor;

    private RecordResource $letter;

    /** What the fake vision model reads, by model. */
    private array $reads = [];

    /** @var list<string> the models asked, in order */
    private array $asked = [];

    /** The gateway answers 503 when it is down. */
    private bool $down = false;

    protected function setUp(): void
    {
        parent::setUp();
        $this->loadBundledVocabularies();
        app(SkosImporter::class)->import(file_get_contents(base_path('tests/Fixtures/role-type.ttl')));
        config(['workspace.ai.gateway_key' => 'test-key', 'workspace.ai.gateway_url' => 'https://ai.example.org/ai/v1']);
        $this->institution = Institution::create(['name' => 'Riverside Archives', 'base_iri' => 'https://riverside.example.org']);
        app(RoleService::class)->seedDefaults($this->institution);
        $this->admin = app(AccountService::class)->create($this->institution, 'Admin', 'admin@riverside.example.org', 'correct horse battery staple');
        app(AccountService::class)->grantTemplateRole($this->admin, 'administrator');
        $this->editor = app(AccountService::class)->create($this->institution, 'Editor', 'editor@riverside.example.org', 'correct horse battery staple');
        app(AccountService::class)->grantTemplateRole($this->editor, 'editor');
        $holder = app(RepositoryService::class)->create($this->institution, 'Riverside Archives', 'en', 'RA');
        $fonds = app(RecordService::class)->create($this->institution, self::LEVEL.'fonds', 'Riverside Parish Council records', 'en', null, $holder, 'RPC');
        $this->letter = app(RecordService::class)->create($this->institution, self::LEVEL.'item', 'Minutes of 3 May 1902', 'en', $fonds, null, '1');
        $this->reads = ['qwen2.5vl:7b-ctx16k' => self::PAGE, 'qwen3.6:27b' => self::PAGE];
        Http::fake(function (ClientRequest $request) {
            if ($this->down) {
                return Http::response('down', 503);
            }
            $model = $request->data()['model'] ?? '';
            $this->asked[] = $model;

            return Http::response(['model' => $model, 'message' => ['role' => 'assistant', 'content' => $this->reads[$model] ?? '']]);
        });
    }

    public function test_nothing_is_asked_without_a_key_with_ai_off_or_over_the_limit(): void
    {
        $gateway = app(Gateway::class);
        $ask = fn () => $gateway->call($this->institution, 'chat', 'ollama/api/chat', ['model' => 'qwen3:8b'], ['input' => 'Hello'], fn ($a) => ['output' => $a['message']['content']]);
        $this->assertThrows($ask, AiUnavailable::class, 'switched off');
        AiSetting::create(['institution_id' => $this->institution->id, 'enabled' => true, 'monthly_limit' => 1]);
        config(['workspace.ai.gateway_key' => '']);
        $this->assertThrows($ask, AiUnavailable::class, 'no AI gateway key');
        config(['workspace.ai.gateway_key' => 'test-key']);
        $ask();
        $this->assertThrows($ask, AiUnavailable::class, 'limit of 1');
        $this->assertSame(['qwen3:8b'], $this->asked, 'only the one call reached the gateway');
        Http::assertSent(fn (ClientRequest $r) => $r->url() === 'https://ai.example.org/ai/v1/ollama/api/chat' && $r->hasHeader('Authorization', 'Bearer test-key'));
    }

    public function test_every_call_is_a_signed_receipt_in_a_chain_that_shows_tampering(): void
    {
        AiSetting::create(['institution_id' => $this->institution->id, 'enabled' => true]);
        $gateway = app(Gateway::class);
        $answer = $gateway->call($this->institution, 'chat', 'ollama/api/chat', ['model' => 'qwen2.5vl:7b-ctx16k'], ['input' => 'Read this', 'user' => $this->editor, 'subject' => $this->letter],
            fn ($a) => ['output' => $a['message']['content'], 'confidence' => 0.9, 'details' => ['note' => 'first']]);
        $this->assertSame(self::PAGE, $answer['read']['output']);
        $this->down = true;
        $this->assertThrows(fn () => $gateway->call($this->institution, 'chat', 'ollama/api/chat', ['model' => 'qwen3:8b'], ['input' => 'Again'], fn ($a) => ['output' => '']),
            AiUnavailable::class, '503');

        [$first, $second] = AiInference::orderBy('seq')->get()->all();
        $this->assertTrue($first->succeeded);
        $this->assertSame(hash('sha256', 'Read this'), $first->input_hash);
        $this->assertSame(hash('sha256', self::PAGE), $first->output_hash);
        $this->assertSame(['record_resources', $this->letter->id, $this->editor->id, 0.9], [$first->subject_table, $first->subject_id, $first->user_id, $first->confidence]);
        $this->assertFalse($second->succeeded);
        $this->assertStringContainsString('HTTP 503', $second->error);
        $this->assertSame($first->entry_hash, $second->prev_hash, 'each receipt holds the hash of the one before');

        $inferences = app(Inferences::class);
        $this->assertSame(['intact' => true, 'rows' => 2, 'problem' => null], $inferences->verify());
        $this->artisan('workspace:ai:verify')->assertSuccessful()->expectsOutputToContain('intact: 2 receipts');
        $this->assertThrows(fn () => DB::transaction(fn () => DB::table('ai_inferences')->where('id', $first->id)->update(['model' => 'other'])), QueryException::class, 'append-only');
        DB::statement('ALTER TABLE ai_inferences DISABLE TRIGGER ai_inferences_append_only');
        DB::table('ai_inferences')->where('id', $first->id)->update(['output_excerpt' => 'Something else']);
        DB::statement('ALTER TABLE ai_inferences ENABLE TRIGGER ai_inferences_append_only');
        $this->assertSame('receipt 0 does not match its hash: it was changed', $inferences->verify()['problem']);
        $this->artisan('workspace:ai:verify')->assertFailed();
    }

    public function test_a_page_is_read_in_strips_checked_against_tesseract_and_proposed_for_review(): void
    {
        $page = $this->page();
        $this->actingAs($this->editor)->post(route('instantiations.read-text', $page))->assertSessionHasErrors('ai');
        AiSetting::create(['institution_id' => $this->institution->id, 'enabled' => true]);
        // The first model reads too little; the fallback model reads the page, as Tesseract does.
        $this->reads['qwen2.5vl:7b-ctx16k'] = 'Minutes';
        $this->actingAs($this->editor)->get(route('instantiations.show', $page))->assertSee('Read the text with AI');
        $this->actingAs($this->editor)->post(route('instantiations.read-text', $page))->assertRedirect();

        $this->assertSame(['qwen2.5vl:7b-ctx16k', 'qwen3.6:27b'], $this->asked, 'the strip that disagreed with Tesseract was read again');
        $proposal = Proposal::whereNotNull('inference_id')->sole();
        $this->assertSame([self::PAGE, 'ai-ocr', 'en', 1.0], [$proposal->value, $proposal->origin_label, $proposal->language, $proposal->confidence]);
        $this->assertStringContainsString('checked against tesseract', strtolower($proposal->evidence));
        $this->assertSame($page->id, $proposal->instantiation_id);
        $this->assertSame(2, AiInference::where('details->reading', $proposal->inference->details['reading'])->count(), 'both readings are receipts');
        $this->actingAs($this->admin)->get(route('proposals.index'))->assertSee('made by qwen2.5vl:7b-ctx16k')->assertSee(route('ai.inference', $proposal->inference_id), false);

        app(ReviewService::class)->accept($proposal, $this->admin, ['value' => self::PAGE.' 1902.']);
        $this->assertSame(self::PAGE.' 1902.', $proposal->fresh()->accepted_value, 'the correction is kept beside what the model said');
        $this->actingAs($this->admin)->get(route('ai.inference', $proposal->inference_id))->assertOk()
            ->assertSee('Admin')->assertSee('The reviewer corrected it before accepting it.')->assertSee($proposal->inference->entry_hash);
        $this->actingAs($this->admin)->get(route('ai.inferences'))->assertOk()->assertSee('qwen3.6:27b');
    }

    public function test_only_administrators_set_ai_up_and_read_the_log(): void
    {
        $this->actingAs($this->editor)->get(route('ai.index'))->assertForbidden();
        $this->actingAs($this->admin)->get(route('ai.index'))->assertOk()->assertSee('AI is switched off for this institution.');
        $this->actingAs($this->admin)->post(route('ai.save'), ['enabled' => 1, 'monthly_limit' => 500, 'ocr_model' => 'qwen2.5vl:7b'])->assertRedirect();
        $this->assertSame([true, 500, 'qwen2.5vl:7b'], [AiSetting::sole()->enabled, AiSetting::sole()->monthly_limit, AiSetting::sole()->ocr_model]);
        $this->actingAs($this->admin)->post(route('ai.save'), ['ocr_model' => 'http://192.168.0.76:11434 x'])->assertSessionHasErrors('ocr_model');
        $this->actingAs($this->admin)->post(route('ai.verify'))->assertSessionHas('chain', ['intact' => true, 'rows' => 0, 'problem' => null]);
    }

    public function test_a_relation_a_model_asserted_is_exported_as_generated_by_it(): void
    {
        $clerk = app(AgentService::class)->create($this->institution, 'person', 'Botha, Maria', 'en');
        $relation = app(RelationService::class)->create($this->letter, 'subject', $clerk, [], null, ['origin' => 'model', 'label' => 'spacy-ner']);
        app(RelationService::class)->assert($relation, $this->admin, true, null, null);
        foreach ([$this->letter->repository ?? $this->letter->parent->repository, $this->letter->parent, $this->letter, $clerk] as $entity) {
            app(PublicationService::class)->apply($entity, 'publish', null, false, $this->admin);
        }
        $json = $this->get(route('api.record', $this->letter->id))->assertOk()->json();
        $this->assertSame('http://www.w3.org/ns/prov#', $json['@context']['prov'] ?? null);
        $text = json_encode($json);
        $this->assertStringContainsString('"prov:wasGeneratedBy"', $text);
        $this->assertStringContainsString('"prov:SoftwareAgent","rdfs:label":"spacy-ner"', $text);
    }

    /** An instantiation whose master is a page image with a line of printed text Tesseract can read. */
    private function page(): Instantiation
    {
        $image = new Imagick;
        $image->newImage(1400, 220, new ImagickPixel('white'));
        $draw = new ImagickDraw;
        $draw->setFontSize(30);
        $draw->setFillColor(new ImagickPixel('black'));
        $image->annotateImage($draw, 30, 110, 0, self::PAGE);
        $image->setImageFormat('png');
        $path = tempnam(sys_get_temp_dir(), 'page').'.png';
        file_put_contents($path, $image->getImageBlob());

        return app(InstantiationService::class)->upload($this->letter, $path, 'minutes-p1.png', 'en', 'Page one', null, 'online', $this->editor);
    }
}
